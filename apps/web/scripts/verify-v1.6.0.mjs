import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("https://rtrzqrxly4mlo.ok.kimi.link", { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
const ids = await page.$$eval("main > section", (els) => els.map((e) => e.id));
const nav = await page.$$eval(".desktop-nav a", (els) => els.map((e) => e.textContent));
const version = await page.evaluate(() => document.body.innerText.match(/网站版本 v[\d.]+/)?.[0]);
console.log("sections:", JSON.stringify(ids));
console.log("nav:", JSON.stringify(nav));
console.log("version:", version);
console.log("errors:", errors);
await page.screenshot({ path: "validation-v1.6.0/top.png" });
await page.evaluate(() => document.getElementById("research").scrollIntoView({ behavior: "instant" }));
await page.waitForTimeout(1200);
await page.screenshot({ path: "validation-v1.6.0/research.png" });
await browser.close();
